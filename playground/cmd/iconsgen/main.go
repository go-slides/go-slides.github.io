// Command iconsgen writes playground/icons/icons_gen.go: the Iconoir glyphs the
// playground draws, and only those.
//
// go-icons/iconoir embeds all ~1500 icons in one embed.FS, which the linker
// cannot cut down: importing it costs every icon in playground.wasm. The
// playground uses about fifty, so this generator finds the names its sources
// pass to icon, act, view and group (and the values of formatGlyphs) and writes
// those SVGs, unmodified, into a Go map. Run it from the playground directory
// after adding or changing an icon:
//
//	go generate ./icons
//
// The test of this command fails when a name in the sources is missing from the
// generated file, or when the file is not what the generator writes now.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/go-icons/iconoir"
	"github.com/spf13/cobra"
)

var osExit = os.Exit

func main() {
	if err := RootCmd().Execute(); err != nil {
		osExit(1)
	}
}

// RootCmd returns the command.
func RootCmd() *cobra.Command {
	var dir, out string
	var check bool
	cmd := &cobra.Command{
		Use:           "iconsgen",
		Short:         "write the Iconoir glyphs the playground uses into icons/icons_gen.go",
		SilenceUsage:  true,
		SilenceErrors: false,
		Args:          cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			names, err := Scan(dir)
			if err != nil {
				return err
			}
			src, err := Generate(names)
			if err != nil {
				return err
			}
			if check {
				have, err := os.ReadFile(out)
				if err != nil {
					return err
				}
				if !bytes.Equal(have, src) {
					return fmt.Errorf("%s is out of date: run go generate ./icons", out)
				}
				return nil
			}
			if err := os.WriteFile(out, src, 0o644); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "%s: %d icons\n", out, len(names))
			return nil
		},
	}
	cmd.Flags().StringVar(&dir, "dir", ".", "the playground package's directory")
	cmd.Flags().StringVar(&out, "out", "icons/icons_gen.go", "the file to write")
	cmd.Flags().BoolVar(&check, "check", false, "fail when --out is not what would be written")
	return cmd
}

// callSites maps a helper of ribbon.go to the index of its glyph argument.
var callSites = map[string]int{"icon": 0, "act": 2, "view": 2, "group": 1}

// Scan returns, sorted, the icon names the package in dir uses: string literals
// in the glyph argument of icon, act, view and group, and the values of the
// formatGlyphs table. A glyph that is not a literal is an error, except the
// parameter the helpers themselves pass along (glyph, g).
func Scan(dir string) ([]string, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, 0)
	if err != nil {
		return nil, err
	}
	set := map[string]bool{}
	var errs []string
	add := func(e ast.Expr, where token.Pos) {
		if lit, ok := e.(*ast.BasicLit); ok && lit.Kind == token.STRING {
			if s, err := strconv.Unquote(lit.Value); err == nil {
				if s != "" {
					set[s] = true
				}
				return
			}
		}
		if id, ok := e.(*ast.Ident); ok && (id.Name == "glyph" || id.Name == "g") {
			return
		}
		errs = append(errs, fmt.Sprintf("%s: an icon name that is not a string literal", fset.Position(where)))
	}
	for _, pkg := range pkgs {
		for _, f := range pkg.Files {
			ast.Inspect(f, func(n ast.Node) bool {
				switch n := n.(type) {
				case *ast.CallExpr:
					if id, ok := n.Fun.(*ast.Ident); ok {
						if i, ok := callSites[id.Name]; ok && i < len(n.Args) {
							add(n.Args[i], n.Pos())
						}
					}
				case *ast.ValueSpec:
					if len(n.Names) == 1 && n.Names[0].Name == "formatGlyphs" && len(n.Values) == 1 {
						if cl, ok := n.Values[0].(*ast.CompositeLit); ok {
							for _, el := range cl.Elts {
								if kv, ok := el.(*ast.KeyValueExpr); ok {
									add(kv.Value, kv.Pos())
								}
							}
						}
					}
				}
				return true
			})
		}
	}
	if len(errs) > 0 {
		return nil, fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	names := make([]string, 0, len(set))
	for s := range set {
		names = append(names, s)
	}
	sort.Strings(names)
	return names, nil
}

// Generate returns the source of icons_gen.go for names, each SVG as iconoir
// serves it. A name iconoir does not have is an error.
func Generate(names []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by cmd/iconsgen; DO NOT EDIT.

// The Iconoir icons (https://iconoir.com) below are
//
//	MIT License
//	Copyright (c) 2021 Luca Burgio
//
// redistributed unmodified from github.com/go-icons/iconoir; the whole licence
// text is in ICONOIR-LICENSE next to this file.

package icons

var svg = map[string]string{
`)
	for _, n := range names {
		s := iconoir.Icon(n)
		if s == "" {
			return nil, fmt.Errorf("iconoir has no icon %q", n)
		}
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(n), strconv.Quote(s))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
