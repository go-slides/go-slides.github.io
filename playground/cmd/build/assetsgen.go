package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

// A digest is the exact size and SHA-256 of a file the build writes.
type digest struct {
	Size int64
	SHA  string // 64 hex digits
}

func digestOf(b []byte) digest {
	s := sha256.Sum256(b)
	return digest{Size: int64(len(b)), SHA: hex.EncodeToString(s[:])}
}

// AssetsGenFile is where the build writes the size and hash of the lazy files
// into the page's module, relative to the module's directory. The render worker
// refuses a fetched body that is not exactly that file (lazyasset.Expect): the
// worker may sit outside the offline cache's scope (a language page), where its
// hash check does not run. The file is written before the module is compiled, so
// what ships is what the build wrote; it is committed so that vet and tests see
// it, and TestAssetsGenIsCurrent makes a stale copy a red CI.
var AssetsGenFile = filepath.Join("cmd", "playground-wasm", "assets_gen.go")

// assetsGen is the source of that file.
func assetsGen(font, pack digest) ([]byte, error) {
	src := fmt.Sprintf(`// Code generated by playground/cmd/build (assetsgen.go); DO NOT EDIT.

package main

// The size and SHA-256 of the files cmd/build writes beside the module, which
// the render worker fetches on demand (lazyfetch.go) and checks.
const (
	mathFontSize   = %d
	mathFontSHA256 = %q

	emojiPackSize   = %d
	emojiPackSHA256 = %q
)
`, font.Size, font.SHA, pack.Size, pack.SHA)
	return format.Source([]byte(src))
}

// writeAssetsGen writes the generated file into the module directory.
func writeAssetsGen(module string, font, pack digest) error {
	b, err := assetsGen(font, pack)
	if err != nil {
		return err
	}
	p := filepath.Join(module, AssetsGenFile)
	if old, err := os.ReadFile(p); err == nil && string(old) == string(b) {
		return nil
	}
	return os.WriteFile(p, b, 0o644)
}
